// Writes src/build.gen.ts: a fingerprint of the rules engine and the card version.
// A room refuses to continue a game that was started on a different engine build, and every
// stored game records both, so stats from different rules are never mixed.
import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const engine = join(here, '../../../packages/engine');
const src = join(engine, 'src');
const hash = createHash('sha256');
for (const f of readdirSync(src).sort()) hash.update(f).update(readFileSync(join(src, f)));
const pkg = JSON.parse(readFileSync(join(engine, 'package.json'), 'utf8'));
const cards = JSON.parse(readFileSync(join(src, 'cards.data.json'), 'utf8'));
const out = `// Generated by scripts/build-info.mjs. Do not edit.
export const ENGINE_VERSION = '${pkg.version}+${hash.digest('hex').slice(0, 10)}';
export const CARD_VERSION = '${cards.version}';
`;
// Only write when something changed, so `wrangler dev` (which watches src/) does not rebuild in a loop.
const target = join(here, '../src/build.gen.ts');
if (!existsSync(target) || readFileSync(target, 'utf8') !== out) writeFileSync(target, out);
console.log(out.trim());
